-- DBA approval, then replace or amend these assumptions before any test setup.
--
-- Assumptions made only to express query requirements:
-- - integer identity IDs are compatible with the JWT middleware's integer check
-- - text fields avoid guessing database length limits not declared by routes
-- - emails are stored lowercase because application writes lowercase values
-- - student semester is 1..4 because public registration enforces that range
-- - users roles are admin/principal/teacher per current staff routes and scripts

CREATE TABLE students (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    full_name TEXT NOT NULL,
    email TEXT NOT NULL CHECK (email = LOWER(email)),
    gender TEXT NOT NULL,
    semester SMALLINT NOT NULL CHECK (semester BETWEEN 1 AND 4),
    roll_number TEXT NOT NULL,
    password_hash TEXT NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT students_email_unique UNIQUE (email)
);

CREATE TABLE users (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    full_name TEXT NOT NULL,
    email TEXT NOT NULL CHECK (email = LOWER(email)),
    password_hash TEXT NOT NULL,
    role TEXT NOT NULL CHECK (role IN ('admin', 'principal', 'teacher')),
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT users_email_unique UNIQUE (email)
);
